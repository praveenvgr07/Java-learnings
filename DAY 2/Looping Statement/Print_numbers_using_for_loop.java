
public class Print_numbers_using_for_loop{
    public static void main(String[] args) {
        
        for(int i = 0; i < 10 ; i++){
            System.out.println(i);
        }
        // while loop
        int j = 1;
        while(j <= 5){
            System.out.println(j);
            j++;
        }

        // do while
        int k = 1;
        do{
            System.out.println(k);
            k++;
        }while(k<=5);

    }
}
